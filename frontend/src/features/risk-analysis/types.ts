export type ReviewStatus = 'unreviewed' | 'investigating' | 'confirmed' | 'dismissed' | 'needs_info'

/** How firmly the platform can state the finding. */
export type FindingClass = 'confirmed_fact' | 'potential_anomaly' | 'unverified_hypothesis'

export type EvidenceStatus =
  | 'supported'
  | 'corroborated'
  | 'contradicted'
  | 'unverified'
  | 'inconclusive'
  | 'no_evidence'

