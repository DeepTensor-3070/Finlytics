export interface FindingMetric {
  label: string
  value: number
  unit: MetricUnit
  currency?: string
  period: string
  /** Prior comparison value, when relevant. */
  prior?: { period: string; value: number }
}

export interface Evidence {
  id: string
  origin: 'internal' | 'external'
  title: string
  excerpt: string
  status: EvidenceStatus
  source?: SourceRef
  url?: string
  retrievedAt?: string
  sourceId?: string
  publisher?: string
  sourceType?: string
  publishedAt?: string
  accessedAt?: string
  reliability?: 'high' | 'medium' | 'low'
  reliabilityAssessment?: string
  borrowerRelevance?: string
  claimSupported?: string
  /** Simulated external evidence must never be shown as live-verified. */
  simulated?: boolean
}

export interface AnalystNote {
  id: string
  author: string
  createdAt: string
  text: string
}

export interface Finding {
  id: string
  assessmentId: string
  companyName: string
  title: string
  summary: string
  whyItMatters: string
  category?: RiskCategory
  triggerSignal?: string
  investigationQuestion?: string
  researchSummary?: string
  severity: Severity
  classification: FindingClass
  evidenceStatus: EvidenceStatus
  reviewStatus: ReviewStatus
  /** 0-1, only when supplied by the backend. */
  confidence?: number
  period: string
  metrics: FindingMetric[]
  evidence: Evidence[]
  followUps: string[]
  recommendedNextSteps?: string[]
  unresolvedQuestions?: string[]
  notes: AnalystNote[]
  detectedAt: string
}

export interface RiskScorecard {
  overallScore: number
  overallRating: 'Low Risk' | 'Moderate Risk' | 'High Risk' | 'Critical Risk'
  financialRisk: { score: number; drivers: string[] }
  businessOperationalRisk: { score: number; drivers: string[] }
  legalRegulatoryRisk: { score: number; drivers: string[] }
  externalResearchRisk: { score: number; drivers: string[] }
  dataCompletenessRisk: { score: number; drivers: string[] }
}

export interface FindingQuery {
  assessmentId?: string
  category?: RiskCategory | ''
  severity?: Severity | ''
  classification?: FindingClass | ''
  reviewStatus?: ReviewStatus | ''
  search?: string
}
